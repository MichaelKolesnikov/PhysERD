#include "ImageExporter.h"
#include "Diagram/DiagramScene.h"
#include <QGraphicsItem>
#include <QImage>
#include <QPainter>
#include <QPdfWriter>
#include <QSvgGenerator>
#include <QPageSize>
#include <cmath>

namespace
{
   const qreal Margin = 40;

   // Selection, hover and grid are hidden while the object lives
   class ExportGuard
   {
   public:
      explicit ExportGuard(DiagramScene* scene) : m_scene(scene)
      {
         m_selection = scene->selectedItems();
         scene->clearSelection();
         scene->setExporting(true);
      }

      ~ExportGuard()
      {
         m_scene->setExporting(false);
         for (QGraphicsItem* item : qAsConst(m_selection))
         {
            item->setSelected(true);
         }
      }

   private:
      DiagramScene* m_scene;
      QList<QGraphicsItem*> m_selection;
   };

   QRectF exportRect(DiagramScene* scene)
   {
      const QRectF content = scene->contentRect();
      return content.isNull() ? QRectF(0, 0, 400, 300) : content.adjusted(-Margin, -Margin, Margin, Margin);
   }
}

QImage ImageExporter::renderImage(DiagramScene *scene, qreal scale)
{
   ExportGuard guard(scene);
   const QRectF source = exportRect(scene);
   QSize size(int(std::ceil(source.width() * scale)), int(std::ceil(source.height() * scale)));
   // keep the image within what QImage can hold
   const qreal limit = 16000;
   if (size.width() > limit || size.height() > limit)
   {
      const qreal shrink = limit / std::max(size.width(), size.height());
      size = QSize(int(size.width() * shrink), int(size.height() * shrink));
   }
   QImage image(size, QImage::Format_ARGB32_Premultiplied);
   image.fill(scene->style().theme.canvas);
   QPainter painter(&image);
   painter.setRenderHints(QPainter::Antialiasing | QPainter::TextAntialiasing | QPainter::SmoothPixmapTransform);
   scene->render(&painter, QRectF(QPointF(0, 0), size), source);
   painter.end();
   return image;
}

bool ImageExporter::exportPng(DiagramScene *scene, const QString &path, qreal scale)
{
   return renderImage(scene, scale).save(path, "PNG");
}

bool ImageExporter::exportSvg(DiagramScene *scene, const QString &path, const QString &title)
{
   ExportGuard guard(scene);
   const QRectF source = exportRect(scene);
   QSvgGenerator generator;
   generator.setFileName(path);
   generator.setTitle(title);
   generator.setDescription(QStringLiteral("Generated by PhysERD"));
   generator.setSize(source.size().toSize());
   generator.setViewBox(QRectF(QPointF(0, 0), source.size()));
   QPainter painter;
   if (!painter.begin(&generator))
   {
      return false;
   }
   painter.setRenderHints(QPainter::Antialiasing | QPainter::TextAntialiasing);
   scene->render(&painter, QRectF(QPointF(0, 0), source.size()), source);
   return painter.end();
}

bool ImageExporter::exportPdf(DiagramScene *scene, const QString &path, const QString &title)
{
   ExportGuard guard(scene);
   const QRectF source = exportRect(scene);
   QPdfWriter writer(path);
   writer.setTitle(title);
   writer.setCreator(QStringLiteral("PhysERD"));
   writer.setResolution(96);
   // one page exactly as big as the diagram
   writer.setPageSize(QPageSize(source.size(), QPageSize::Point, QString(), QPageSize::ExactMatch));
   writer.setPageMargins(QMarginsF(0, 0, 0, 0));
   QPainter painter;
   if (!painter.begin(&writer))
   {
      return false;
   }
   painter.setRenderHints(QPainter::Antialiasing | QPainter::TextAntialiasing);
   const QRect target = painter.viewport();
   scene->render(&painter, target, source, Qt::KeepAspectRatio);
   return painter.end();
}
