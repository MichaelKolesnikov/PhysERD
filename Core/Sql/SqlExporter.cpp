#include "SqlExporter.h"
#include "DTO/SchemaDTO.h"
#include <QSet>
#include <QStringList>

using Dialect = SqlExporter::Dialect;

namespace
{
   QString sqlString(const QString& text)
   {
      return '\'' + QString(text).replace('\'', QStringLiteral("''")) + '\'';
   }

   class Writer
   {
   public:
      Writer(const SchemaDTO& schema, Dialect dialect)
         : m_schema(schema), m_dialect(dialect)
      {
         for (const TableDTO& table : schema.tables)
         {
            m_tableNames.insert(table.fullName());
         }
      }

      QString run()
      {
         m_out = QStringLiteral("-- SQL dump generated by PhysERD\n-- Database: %1\n").arg(SqlExporter::dialectName(m_dialect));
         if (m_schema.project.defined && !m_schema.project.name.isEmpty())
         {
            m_out += QStringLiteral("-- Project: %1\n").arg(m_schema.project.name);
         }
         m_out += '\n';

         writeSchemas();
         if (m_dialect == Dialect::PostgreSQL)
         {
            writePostgresEnums();
         }
         for (const TableDTO& table : m_schema.tables)
         {
            writeTable(table);
         }
         for (const RefDTO& ref : m_schema.refs)
         {
            if (ref.leftCardinality == Cardinality::Many && ref.rightCardinality == Cardinality::Many)
            {
               writeJunctionTable(ref);
            }
         }
         writeComments();
         for (const TableDTO& table : m_schema.tables)
         {
            writeIndexes(table);
         }
         writeForeignKeys();

         while (m_out.endsWith(QLatin1String("\n\n")))
         {
            m_out.chop(1);
         }
         return m_out;
      }

   private:
      QString quote(const QString& identifier) const
      {
         switch (m_dialect)
         {
         case Dialect::MySQL:
            return '`' + QString(identifier).replace('`', QStringLiteral("``")) + '`';
         case Dialect::SQLServer:
            return '[' + QString(identifier).replace(']', QStringLiteral("]]")) + ']';
         case Dialect::PostgreSQL:
         default:
            return '"' + QString(identifier).replace('"', QStringLiteral("\"\"")) + '"';
         }
      }

      QString tableName(const QString& schema, const QString& name) const
      {
         return schema.isEmpty() ? quote(name) : quote(schema) + '.' + quote(name);
      }

      QString columnList(const QStringList& columns) const
      {
         QStringList quoted;
         for (const QString& column : columns)
         {
            quoted << quote(column);
         }
         return quoted.join(QStringLiteral(", "));
      }

      QString endStatement() const
      {
         return m_dialect == Dialect::SQLServer ? QStringLiteral(";\nGO\n\n") : QStringLiteral(";\n\n");
      }

      void writeSchemas()
      {
         QStringList schemas;
         auto add = [&](const QString& schema) {
            const bool isDefault = schema.isEmpty() || (m_dialect == Dialect::PostgreSQL && schema == QLatin1String("public"))
                  || (m_dialect == Dialect::SQLServer && schema == QLatin1String("dbo"));
            if (!isDefault && !schemas.contains(schema))
            {
               schemas << schema;
            }
         };
         for (const TableDTO& table : m_schema.tables)
         {
            add(table.schema);
         }
         if (m_dialect == Dialect::PostgreSQL)
         {
            for (const EnumDTO& enumDTO : m_schema.enums)
            {
               add(enumDTO.schema);
            }
         }
         for (const QString& schema : qAsConst(schemas))
         {
            if (m_dialect == Dialect::SQLServer)
            {
               m_out += QStringLiteral("CREATE SCHEMA ") + quote(schema) + endStatement();
            }
            else
            {
               m_out += QStringLiteral("CREATE SCHEMA IF NOT EXISTS ") + quote(schema) + endStatement();
            }
         }
      }

      void writePostgresEnums()
      {
         for (const EnumDTO& enumDTO : m_schema.enums)
         {
            QStringList values;
            for (const EnumValueDTO& value : enumDTO.values)
            {
               values << QStringLiteral("  ") + sqlString(value.name);
            }
            m_out += QStringLiteral("CREATE TYPE ") + tableName(enumDTO.schema, enumDTO.name) + QStringLiteral(" AS ENUM (\n")
                  + values.join(QStringLiteral(",\n")) + QStringLiteral("\n)") + endStatement();
         }
      }

      QString enumValues(const EnumDTO& enumDTO) const
      {
         QStringList values;
         for (const EnumValueDTO& value : enumDTO.values)
         {
            values << sqlString(value.name);
         }
         return values.join(QStringLiteral(", "));
      }

      // The SQL type of a column, without the increment
      QString columnType(const ColumnDTO& column) const
      {
         const EnumDTO* enumDTO = m_schema.enumForType(column.type);
         if (!enumDTO)
         {
            return column.type;
         }
         switch (m_dialect)
         {
         case Dialect::MySQL:
            return QStringLiteral("ENUM (") + enumValues(*enumDTO) + ')';
         case Dialect::SQLServer:
            return QStringLiteral("nvarchar(255)");
         case Dialect::PostgreSQL:
         default:
            return tableName(enumDTO->schema, enumDTO->name);
         }
      }

      QString columnTypeWithIncrement(const ColumnDTO& column) const
      {
         const QString type = columnType(column);
         if (!column.increment)
         {
            return type;
         }
         switch (m_dialect)
         {
         case Dialect::MySQL:
            return type + QStringLiteral(" AUTO_INCREMENT");
         case Dialect::SQLServer:
            return type + QStringLiteral(" IDENTITY(1, 1)");
         case Dialect::PostgreSQL:
         default:
         {
            const QString lower = type.toLower();
            if (lower == QLatin1String("int") || lower == QLatin1String("integer") || lower == QLatin1String("int4"))
            {
               return QStringLiteral("SERIAL");
            }
            if (lower == QLatin1String("bigint") || lower == QLatin1String("int8"))
            {
               return QStringLiteral("BIGSERIAL");
            }
            if (lower == QLatin1String("smallint") || lower == QLatin1String("int2"))
            {
               return QStringLiteral("SMALLSERIAL");
            }
            return type + QStringLiteral(" GENERATED BY DEFAULT AS IDENTITY");
         }
         }
      }

      QString defaultValue(const ColumnDTO& column) const
      {
         switch (column.defaultKind)
         {
         case ColumnDTO::StringDefault:
            return sqlString(column.defaultValue);
         case ColumnDTO::ExpressionDefault:
            return '(' + column.defaultValue + ')';
         case ColumnDTO::BooleanDefault:
            if (m_dialect == Dialect::SQLServer)
            {
               return column.defaultValue == QLatin1String("true") ? QStringLiteral("1") : QStringLiteral("0");
            }
            return column.defaultValue;
         case ColumnDTO::NullDefault:
            return QStringLiteral("NULL");
         default:
            return column.defaultValue;
         }
      }

      // Columns of the primary key; a pk index wins over pk columns
      static QStringList primaryKey(const TableDTO& table)
      {
         for (const IndexDTO& index : table.indexes)
         {
            if (index.pk)
            {
               QStringList columns;
               for (const IndexColumnDTO& column : index.columns)
               {
                  columns << column.value;
               }
               return columns;
            }
         }
         QStringList columns;
         for (const ColumnDTO& column : table.columns)
         {
            if (column.pk)
            {
               columns << column.name;
            }
         }
         return columns;
      }

      void writeTable(const TableDTO& table)
      {
         const QStringList pk = primaryKey(table);
         const bool inlinePk = pk.size() == 1 && table.columnIndex(pk.first()) >= 0 && table.columns[table.columnIndex(pk.first())].pk;

         QStringList lines;
         for (const ColumnDTO& column : table.columns)
         {
            QString line = QStringLiteral("  ") + quote(column.name) + ' ' + columnTypeWithIncrement(column);
            if (inlinePk && column.pk)
            {
               line += QStringLiteral(" PRIMARY KEY");
            }
            if (column.unique)
            {
               line += QStringLiteral(" UNIQUE");
            }
            if (column.notNull)
            {
               line += QStringLiteral(" NOT NULL");
            }
            if (column.defaultKind != ColumnDTO::NoDefault)
            {
               line += QStringLiteral(" DEFAULT ") + defaultValue(column);
            }
            if (m_dialect == Dialect::SQLServer)
            {
               if (const EnumDTO* enumDTO = m_schema.enumForType(column.type))
               {
                  line += QStringLiteral(" CHECK (") + quote(column.name) + QStringLiteral(" IN (") + enumValues(*enumDTO) + QStringLiteral("))");
               }
            }
            if (m_dialect == Dialect::MySQL && !column.note.isEmpty())
            {
               line += QStringLiteral(" COMMENT ") + sqlString(column.note);
            }
            lines << line;
         }
         if (!pk.isEmpty() && !inlinePk)
         {
            lines << QStringLiteral("  PRIMARY KEY (") + columnList(pk) + ')';
         }

         m_out += QStringLiteral("CREATE TABLE ") + tableName(table.schema, table.name) + QStringLiteral(" (\n") + lines.join(QStringLiteral(",\n")) + QStringLiteral("\n)");
         if (m_dialect == Dialect::MySQL && !table.note.isEmpty())
         {
            m_out += QStringLiteral(" COMMENT=") + sqlString(table.note);
         }
         m_out += endStatement();
      }

      const TableDTO* table(const RefEndpointDTO& endpoint) const
      {
         return m_schema.table(endpoint.tableFullName());
      }

      QString junctionName(const RefDTO& ref)
      {
         QString name = ref.left.table + '_' + ref.right.table;
         const QString schema = ref.left.schema;
         QString candidate = name;
         for (int i = 1; m_tableNames.contains(qualifiedName(schema, candidate)); ++i)
         {
            candidate = name + '_' + QString::number(i);
         }
         m_tableNames.insert(qualifiedName(schema, candidate));
         return candidate;
      }

      void writeJunctionTable(const RefDTO& ref)
      {
         const TableDTO* left = table(ref.left);
         const TableDTO* right = table(ref.right);
         if (!left || !right)
         {
            return;
         }
         const QString name = junctionName(ref);
         QStringList lines;
         QStringList leftColumns;
         QStringList rightColumns;
         auto addColumns = [&](const TableDTO* side, const QStringList& columns, QStringList& names) {
            for (const QString& columnName : columns)
            {
               const int index = side->columnIndex(columnName);
               const QString type = index < 0 ? QStringLiteral("integer") : columnType(side->columns[index]);
               QString junctionColumn = side->name + '_' + columnName;
               while (leftColumns.contains(junctionColumn) || rightColumns.contains(junctionColumn))
               {
                  junctionColumn += '_';
               }
               names << junctionColumn;
               lines << QStringLiteral("  ") + quote(junctionColumn) + ' ' + type + QStringLiteral(" NOT NULL");
            }
         };
         addColumns(left, ref.left.columns, leftColumns);
         addColumns(right, ref.right.columns, rightColumns);
         lines << QStringLiteral("  PRIMARY KEY (") + columnList(leftColumns + rightColumns) + ')';

         m_out += QStringLiteral("CREATE TABLE ") + tableName(ref.left.schema, name) + QStringLiteral(" (\n") + lines.join(QStringLiteral(",\n")) + QStringLiteral("\n)") + endStatement();
         m_junctions << Junction{ref, ref.left.schema, name, leftColumns, rightColumns};
      }

      void writeComments()
      {
         if (m_dialect == Dialect::MySQL)
         {
            return; // written inline
         }
         for (const TableDTO& table : m_schema.tables)
         {
            if (!table.note.isEmpty())
            {
               writeComment(table, QString(), table.note);
            }
            for (const ColumnDTO& column : table.columns)
            {
               if (!column.note.isEmpty())
               {
                  writeComment(table, column.name, column.note);
               }
            }
         }
      }

      void writeComment(const TableDTO& table, const QString& column, const QString& note)
      {
         if (m_dialect == Dialect::PostgreSQL)
         {
            if (column.isEmpty())
            {
               m_out += QStringLiteral("COMMENT ON TABLE ") + tableName(table.schema, table.name);
            }
            else
            {
               m_out += QStringLiteral("COMMENT ON COLUMN ") + tableName(table.schema, table.name) + '.' + quote(column);
            }
            m_out += QStringLiteral(" IS ") + sqlString(note) + endStatement();
            return;
         }

         const QString schema = table.schema.isEmpty() ? QStringLiteral("dbo") : table.schema;
         m_out += QStringLiteral("EXEC sp_addextendedproperty\n@name = N'%1',\n@value = %2,\n@level0type = N'Schema', @level0name = %3,\n@level1type = N'Table',  @level1name = %4")
               .arg(column.isEmpty() ? QStringLiteral("Table_Description") : QStringLiteral("Column_Description"), sqlString(note), sqlString(schema), sqlString(table.name));
         if (!column.isEmpty())
         {
            m_out += QStringLiteral(",\n@level2type = N'Column', @level2name = ") + sqlString(column);
         }
         m_out += endStatement();
      }

      void writeIndexes(const TableDTO& table)
      {
         int counter = 0;
         for (const IndexDTO& index : table.indexes)
         {
            if (index.pk)
            {
               continue;
            }
            ++counter;
            QStringList columns;
            for (const IndexColumnDTO& column : index.columns)
            {
               columns << (column.isExpression ? '(' + column.value + ')' : quote(column.value));
            }
            QString name = index.name;
            if (name.isEmpty() && m_dialect != Dialect::PostgreSQL)
            {
               name = QStringLiteral("%1_index_%2").arg(table.name).arg(counter);
            }

            QString statement = index.unique ? QStringLiteral("CREATE UNIQUE INDEX ") : QStringLiteral("CREATE INDEX ");
            if (!name.isEmpty())
            {
               statement += quote(name) + ' ';
            }
            statement += QStringLiteral("ON ") + tableName(table.schema, table.name);
            if (m_dialect == Dialect::PostgreSQL && !index.type.isEmpty())
            {
               statement += QStringLiteral(" USING ") + index.type.toUpper();
            }
            statement += QStringLiteral(" (") + columns.join(QStringLiteral(", ")) + ')';
            if (m_dialect == Dialect::MySQL && !index.type.isEmpty())
            {
               statement += QStringLiteral(" USING ") + index.type.toUpper();
            }
            m_out += statement + endStatement();
         }
      }

      QString foreignKey(const QString& fromSchema, const QString& fromTable, const QStringList& fromColumns,
                         const QString& toSchema, const QString& toTable, const QStringList& toColumns,
                         const RefDTO& ref) const
      {
         QString statement = QStringLiteral("ALTER TABLE ") + tableName(fromSchema, fromTable) + QStringLiteral(" ADD ");
         if (!ref.name.isEmpty())
         {
            statement += QStringLiteral("CONSTRAINT ") + quote(ref.name) + ' ';
         }
         statement += QStringLiteral("FOREIGN KEY (") + columnList(fromColumns) + QStringLiteral(") REFERENCES ")
               + tableName(toSchema, toTable) + QStringLiteral(" (") + columnList(toColumns) + ')';
         if (!ref.onDelete.isEmpty())
         {
            statement += QStringLiteral(" ON DELETE ") + ref.onDelete.toUpper();
         }
         if (!ref.onUpdate.isEmpty())
         {
            statement += QStringLiteral(" ON UPDATE ") + ref.onUpdate.toUpper();
         }
         return statement + endStatement();
      }

      void writeForeignKeys()
      {
         for (const RefDTO& ref : m_schema.refs)
         {
            const RefEndpointDTO* from = &ref.left;
            const RefEndpointDTO* to = &ref.right;
            if (ref.leftCardinality == Cardinality::Many && ref.rightCardinality == Cardinality::Many)
            {
               continue;
            }
            if (ref.leftCardinality == Cardinality::One && ref.rightCardinality == Cardinality::Many)
            {
               std::swap(from, to);
            }
            m_out += foreignKey(from->schema, from->table, from->columns, to->schema, to->table, to->columns, ref);
         }

         for (const Junction& junction : qAsConst(m_junctions))
         {
            RefDTO plain = junction.ref;
            plain.name.clear();
            m_out += foreignKey(junction.schema, junction.name, junction.leftColumns, junction.ref.left.schema, junction.ref.left.table, junction.ref.left.columns, plain);
            m_out += foreignKey(junction.schema, junction.name, junction.rightColumns, junction.ref.right.schema, junction.ref.right.table, junction.ref.right.columns, plain);
         }
      }

      struct Junction
      {
         RefDTO ref;
         QString schema;
         QString name;
         QStringList leftColumns;
         QStringList rightColumns;
      };

      const SchemaDTO& m_schema;
      Dialect m_dialect;
      QString m_out;
      QSet<QString> m_tableNames;
      QVector<Junction> m_junctions;
   };
}

QString SqlExporter::exportSchema(const SchemaDTO &schema, Dialect dialect)
{
   return Writer(schema, dialect).run();
}

SqlExporter::Dialect SqlExporter::dialectFromDatabaseType(const QString &databaseType, Dialect fallback)
{
   const QString type = databaseType.toLower().remove(' ');
   if (type.startsWith(QLatin1String("postgres")))
   {
      return Dialect::PostgreSQL;
   }
   if (type == QLatin1String("mysql") || type == QLatin1String("mariadb"))
   {
      return Dialect::MySQL;
   }
   if (type == QLatin1String("sqlserver") || type == QLatin1String("mssql") || type == QLatin1String("microsoftsqlserver"))
   {
      return Dialect::SQLServer;
   }
   return fallback;
}

QString SqlExporter::dialectName(Dialect dialect)
{
   switch (dialect)
   {
   case Dialect::MySQL:
      return QStringLiteral("MySQL");
   case Dialect::SQLServer:
      return QStringLiteral("SQL Server");
   case Dialect::PostgreSQL:
   default:
      return QStringLiteral("PostgreSQL");
   }
}
